#!/usr/bin/env bash
# Centralized configuration for batch-bench pipeline.
# Source this file, then all env vars with defaults are set and exported.

set -euo pipefail

_CFG_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$_CFG_DIR/../.." && pwd)"

DATA_STORE="${DATA_STORE:-$REPO_ROOT/.cache/skillcomptest}"
PLATFORM="${PLATFORM:-linux}"
SKILL="${SKILL:-}"
SOURCE="${SOURCE:-}"
MAX_PARALLEL="${MAX_PARALLEL:-12}"
S1_PARALLEL="${S1_PARALLEL:-8}"
S2_PARALLEL="${S2_PARALLEL:-12}"
TASK_PARALLEL="${TASK_PARALLEL:-6}"
PIPELINE_MODE="${PIPELINE_MODE:-streaming}"
MAX_AGENT_PARALLEL="${MAX_AGENT_PARALLEL:-24}"
TIMEOUT_PER_STAGE="${TIMEOUT_PER_STAGE:-1200}"
TIMEOUT_PER_TASK="${TIMEOUT_PER_TASK:-150}"
CLAUDE_MODEL="${CLAUDE_MODEL:-deepseek-v4-flash}"
SAMPLE_CLAUDE_MODEL="${SAMPLE_CLAUDE_MODEL:-deepseek-v4-flash}"
EXEC_CLAUDE_MODEL="${EXEC_CLAUDE_MODEL:-$CLAUDE_MODEL}"
CLAUDE_OUTPUT_FORMAT="${CLAUDE_OUTPUT_FORMAT:-json}"
CLAUDE_NO_SESSION_PERSISTENCE="${CLAUDE_NO_SESSION_PERSISTENCE:-1}"
RUNNER="${RUNNER:-claude}"
KIMI_THINKING="${KIMI_THINKING:-on}"
TASK_COUNT="${TASK_COUNT:-6}"
TASK_DESIGN_MODEL="${TASK_DESIGN_MODEL:-ClaudeCode_M2.7}"
QUEUE_POLICY="${QUEUE_POLICY:-untested}"
SKILL_LIST="${SKILL_LIST:-}"
BATCH_ID="${BATCH_ID:-$(date +%Y%m%d-%H%M%S)-$PLATFORM}"
SAMPLE_REFRESH_POLICY="${SAMPLE_REFRESH_POLICY:-never}"
ALLOW_RERUN_COMPLETE="${ALLOW_RERUN_COMPLETE:-0}"
MAX_RETRIES="${MAX_RETRIES:-2}"
RETRY_BACKOFF_BASE="${RETRY_BACKOFF_BASE:-2}"
ALLOW_WRITABLE_SKILL_SOURCE="${ALLOW_WRITABLE_SKILL_SOURCE:-0}"
MIN_FREE_MB="${MIN_FREE_MB:-1024}"
MOCK_CLAUDE="${MOCK_CLAUDE:-}"
TASK_QUEUE_FILE="$DATA_STORE/.batch-task-queue.txt"
QUEUE_DIR="$DATA_STORE/queues"
NAMED_TASK_QUEUE_FILE="$QUEUE_DIR/$BATCH_ID.queue"
BATCH_PLAN_FILE="$QUEUE_DIR/$BATCH_ID.plan.json"
SAMPLE_REFRESH_FILE="$QUEUE_DIR/$BATCH_ID.refresh-samples"
EVENT_LOG="$DATA_STORE/pipeline_events.jsonl"
PROGRESS_FILE="$DATA_STORE/.pipeline_progress.json"
LOCK_FILE="$DATA_STORE/.batch-bench.lock"
NAMED_BATCH_REPORT="$QUEUE_DIR/$BATCH_ID.report.json"
LATEST_BATCH_REPORT="$DATA_STORE/batch-report.json"
BATCH_REPORT="$NAMED_BATCH_REPORT"

configure_claude_provider() {
  if [ -n "${OPENROUTER_API_KEY:-}" ]; then
    export OPENROUTER_API_KEY
    ANTHROPIC_BASE_URL="${ANTHROPIC_BASE_URL:-https://openrouter.ai/api}"
    ANTHROPIC_BASE_URL="${ANTHROPIC_BASE_URL%/}"
    export ANTHROPIC_BASE_URL
    export ANTHROPIC_AUTH_TOKEN="${ANTHROPIC_AUTH_TOKEN:-$OPENROUTER_API_KEY}"
    export ANTHROPIC_API_KEY=""
    export CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC="${CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC:-1}"
    export CLAUDE_SETTING_SOURCES="${CLAUDE_SETTING_SOURCES:-project,local}"
  elif [ -n "${ANTHROPIC_BASE_URL:-}" ] || [ -n "${ANTHROPIC_AUTH_TOKEN:-}" ]; then
    if [ -n "${ANTHROPIC_BASE_URL:-}" ]; then
      ANTHROPIC_BASE_URL="${ANTHROPIC_BASE_URL%/}"
      export ANTHROPIC_BASE_URL
    fi
    if [ -n "${ANTHROPIC_AUTH_TOKEN:-}" ]; then
      export ANTHROPIC_AUTH_TOKEN
      export ANTHROPIC_API_KEY=""
    elif [ "${ANTHROPIC_API_KEY+x}" = "x" ]; then
      export ANTHROPIC_API_KEY
    fi
    export CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC="${CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC:-1}"
    export CLAUDE_SETTING_SOURCES="${CLAUDE_SETTING_SOURCES:-project,local}"
  else
    [ "${ANTHROPIC_API_KEY+x}" = "x" ] && export ANTHROPIC_API_KEY
    [ -n "${CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC:-}" ] && export CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC
    [ -n "${CLAUDE_SETTING_SOURCES:-}" ] && export CLAUDE_SETTING_SOURCES
  fi
  return 0
}

configure_claude_provider

SKILLS_DIR="$DATA_STORE/skills-repo"
if [ ! -d "$SKILLS_DIR" ]; then
  SKILLS_DIR="$DATA_STORE/SkillsRepo"
fi

SAMPLES_DIR="$DATA_STORE/samples"
EXEC_DIR="$DATA_STORE/exec/$PLATFORM"
export DATA_STORE PLATFORM RUNNER TASK_DESIGN_MODEL REPO_ROOT
export SAMPLES_DIR EXEC_DIR SKILLS_DIR
export TIMEOUT_PER_STAGE TIMEOUT_PER_TASK S1_PARALLEL S2_PARALLEL TASK_PARALLEL
export PIPELINE_MODE MAX_AGENT_PARALLEL
export CLAUDE_MODEL SAMPLE_CLAUDE_MODEL EXEC_CLAUDE_MODEL TASK_COUNT
export CLAUDE_OUTPUT_FORMAT CLAUDE_NO_SESSION_PERSISTENCE
export QUEUE_POLICY SKILL_LIST BATCH_ID SAMPLE_REFRESH_POLICY ALLOW_RERUN_COMPLETE
export QUEUE_DIR NAMED_TASK_QUEUE_FILE BATCH_PLAN_FILE SAMPLE_REFRESH_FILE
export NAMED_BATCH_REPORT LATEST_BATCH_REPORT BATCH_REPORT
export MAX_RETRIES RETRY_BACKOFF_BASE MOCK_CLAUDE EVENT_LOG PROGRESS_FILE
export ALLOW_WRITABLE_SKILL_SOURCE
